#!/usr/bin/env python3
"""Add or remove a Developer-area app's dev/QA AdGuard rewrite.

Usage: app_dns.py add|remove <slug> <dev|qa> [--apps-file F] [--main-vars F]

Edits ansible/adguard/roles/adguard/vars/apps-rewrites.yml (the generated file
the adguard role merges into its rewrite lists) and prints one JSON line:
{"changed": bool, "domain": "...", "env": "..."}. Idempotent: adding a present
domain or removing an absent one reports changed=false and writes nothing.
Refuses slugs that are invalid or reserved, and hostnames that the hand-
maintained lists already own. Exit 2 on refusal, 1 on bad usage.

Prod is not handled here: prod app hostnames resolve through Cloudflare
(traefik-gitops sync-dns.yml reconciles apps.yml).
"""
import argparse
import json
import re
import sys

import yaml

SLUG_RE = re.compile(r"^[a-z][a-z0-9-]{1,30}[a-z0-9]$")
DOMAIN = "databaes.net"
# Keep in step with ops-portal-apps internal/httpapi/reserved.go and
# traefik-gitops scripts/validate-apps-routes.py. The collision check against
# the hand-maintained lists below is the part that cannot drift.
RESERVED = {
    "ops", "api", "www", "auth", "sso", "authentik", "admin", "root", "login", "signup",
    "mail", "smtp", "vault", "traefik", "nats", "grafana", "prometheus", "loki", "tempo",
    "wiki", "wikijs", "cloud", "nextcloud", "landing", "status", "streambox", "tomajflix",
    "plex", "mcc", "chesscoach", "wedding", "investing", "minecraft", "mc-console", "ai-dev",
    "zigbee", "rancher", "signoz", "sonarr", "radarr", "prowlarr", "seerr", "homelab",
    "databaes", "dev", "qa", "prod", "default", "localhost", "problem-reports", "spend",
    "kube-system", "kube-public", "monitoring", "cert-manager",
}
PREFIXES = ("ops-", "app-", "kube-", "arc-", "authentik-")
SUFFIXES = ("-dev", "-qa", "-prod")
KEYS = {"dev": "adguard_apps_dev_rewrites", "qa": "adguard_apps_qa_rewrites"}
# Domains removed by this script. The adguard role deletes their rewrites on
# every run: it only cleans up domains it knows about, so a domain that simply
# left the lists would keep resolving forever (found on dev, 2026-11-14).
REMOVED_KEY = "adguard_apps_removed"
HEADER = """# GENERATED by .github/workflows/app-dns.yml (scripts/app_dns.py). Do not edit by hand.
# Dev/QA hostnames of Developer-area apps. The adguard role merges these into
# adguard_dev_rewrites / adguard_qa_rewrites, so they follow the same rules:
# every AdGuard answers for every env's hostnames. Prod app hostnames need no
# entry here: they resolve through Cloudflare (traefik-gitops sync-dns.yml).
"""


class Refused(Exception):
    pass


def check_slug(slug):
    if not SLUG_RE.match(slug):
        raise Refused(f"invalid slug {slug!r}")
    if slug in RESERVED or slug.startswith(PREFIXES) or slug.endswith(SUFFIXES):
        raise Refused(f"slug {slug!r} is reserved")


def render(data):
    out = HEADER
    for env in ("dev", "qa"):
        items = sorted(set(data[KEYS[env]]))
        if not items:
            out += f"{KEYS[env]}: []\n"
        else:
            out += f"{KEYS[env]}:\n" + "".join(f"  - domain: {d}\n" for d in items)
    gone = sorted(set(data.get(REMOVED_KEY, [])))
    out += "# Removed app hostnames: the role deletes any rewrite still present for these.\n"
    out += f"{REMOVED_KEY}: []\n" if not gone else f"{REMOVED_KEY}:\n" + "".join(f"  - {d}\n" for d in gone)
    return out


def load_apps(path):
    with open(path) as f:
        raw = yaml.safe_load(f) or {}
    unknown = set(raw) - set(KEYS.values()) - {REMOVED_KEY}
    if unknown:
        raise Refused(f"unexpected keys in {path}: {sorted(unknown)}")
    data = {k: [e["domain"] for e in (raw.get(k) or [])] for k in KEYS.values()}
    data[REMOVED_KEY] = list(raw.get(REMOVED_KEY) or [])
    return data


def handmade_domains(path):
    with open(path) as f:
        raw = yaml.safe_load(f) or {}
    return {e["domain"] for k in ("adguard_dev_rewrites", "adguard_qa_rewrites", "adguard_prod_rewrites")
            for e in (raw.get(k) or [])}


def run(action, slug, env, apps_file, main_vars):
    if env not in KEYS:
        raise Refused("env must be dev or qa (prod resolves through Cloudflare)")
    check_slug(slug)
    domain = f"{slug}-{env}.{DOMAIN}"
    if domain in handmade_domains(main_vars):
        raise Refused(f"{domain} is owned by the hand-maintained rewrite lists")
    data = load_apps(apps_file)
    cur = data[KEYS[env]]
    gone = data[REMOVED_KEY]
    if action == "add":
        changed = domain not in cur or domain in gone
        if domain not in cur:
            cur.append(domain)
        data[REMOVED_KEY] = [d for d in gone if d != domain]
    else:
        # Tombstone even when the domain is not listed, so a removal whose first
        # attempt half-failed can still be finished by repeating it.
        changed = domain in cur or domain not in gone
        data[KEYS[env]] = [d for d in cur if d != domain]
        if domain not in gone:
            gone.append(domain)
    if changed:
        with open(apps_file, "w") as f:
            f.write(render(data))
    return {"changed": changed, "domain": domain, "env": env}


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=("add", "remove"))
    ap.add_argument("slug")
    ap.add_argument("env")
    ap.add_argument("--apps-file", default="ansible/adguard/roles/adguard/vars/apps-rewrites.yml")
    ap.add_argument("--main-vars", default="ansible/adguard/roles/adguard/vars/main.yml")
    a = ap.parse_args(argv[1:])
    try:
        print(json.dumps(run(a.action, a.slug, a.env, a.apps_file, a.main_vars)))
    except Refused as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
